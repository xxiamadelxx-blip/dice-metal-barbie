"""500,000 real indexed GLB triangles built from FIXED high fidelity Boolean engraved source.
Uses the previously approved real 59,276-triangle authored GLB as actual input.
This is NOT 500k GPU MultiMesh instances. This is a Blender geometry/GLB
prototype; art approval, on-device Android FPS and external obsidian source OPEN.
Run: blender -b -t 3 -P tools/blender/build_d20_master_500k.py -- INPUT.glb OUT_DIR
"""
import bpy
import bmesh
import sys
import json
import hashlib
import math
from pathlib import Path
from mathutils import Vector

TARGET = 500000
ARG = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
assert len(ARG) == 2, "Usage: INPUT.glb OUTPUT_DIRECTORY"
SOURCE, OUT = Path(ARG[0]).resolve(), Path(ARG[1]).resolve()
OUT.mkdir(parents=True, exist_ok=True)
assert SOURCE.exists(), SOURCE
source_sha=hashlib.sha256(SOURCE.read_bytes()).hexdigest()
source_receipt=SOURCE.parent/"manifest.json"
assert source_receipt.is_file(), "Source must be generated by repaired authoring script and include a manifest"
source_record=json.loads(source_receipt.read_text())
assert source_record["source_glb_sha256"]==source_sha, ("Unaudited source mesh",source_sha)
assert source_record.get("glyph_size")==.43
print("D20_V2_REPAIRED_GLTF_SOURCE",source_sha,flush=True)
bpy.ops.object.select_all(action="SELECT")
bpy.ops.object.delete(use_global=False)
bpy.ops.import_scene.gltf(filepath=str(SOURCE))
objects = [obj for obj in bpy.context.scene.objects if obj.type == "MESH"]
stone = [obj for obj in objects if obj.name.startswith("D20_Engraved")]
gold = [obj for obj in objects if obj.name.startswith("Gold_")]
assert len(stone) == 1 and len(gold) == 20, [(o.name, len(o.data.polygons)) for o in objects]
assert len(objects) == 21, "No extra meshes"
source_triangles=sum(len(o.data.polygons) for o in objects)
assert 50000 < source_triangles < 500000, ("Unexpected source tessellation",source_triangles)
assert source_record["num_original_glyphs"]==20
print("D20_V2_AUTHORED_HIGHRES_SOURCE_TRIS",source_triangles,flush=True)
for obj in objects:
    assert all(len(face.vertices) == 3 for face in obj.data.polygons)
# Mesh subdivision is performed AFTER corrected higher-resolution glyph contours,
# deeper cutter Boolean and final microbevel. This is for actual mesh density,
# not a trick that is purported to fix shape by subdividing already-broken cuts.
def refine(obj,cuts):
    bm=bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.triangulate(bm,faces=list(bm.faces))
    if cuts:
        bmesh.ops.subdivide_edges(bm,edges=list(bm.edges),cuts=cuts,use_grid_fill=True)
        bmesh.ops.triangulate(bm,faces=list(bm.faces))
    bm.normal_update()
    return bm

source_stone=len(stone[0].data.polygons)
source_gold=sum(len(o.data.polygons) for o in gold)
# A new high-res source may already be >100k, unlike old 59k master.
# Select a REAL geometry budget based on measured actual mesh triangles.
options=[]
for stone_cuts in range(0,4):
    for gold_cuts in range(0,3):
        estimate=source_stone*(stone_cuts+1)**2+source_gold*(gold_cuts+1)**2
        if 170000 <= estimate <=TARGET and estimate%2==TARGET%2:
            # Prefer meaningful stone geometry and zero gold over-tessellation.
            score=(abs(estimate-300000)
                    +max(0,160000-source_stone*(stone_cuts+1)**2)*.8
                    +gold_cuts*50000)
            options.append((score,stone_cuts,gold_cuts,estimate))
assert options,("Repaired source needs a new tessellation plan",source_stone,source_gold,TARGET)
score,stone_cuts,gold_cuts,estimated=min(options)
meshes=[]
for obj in objects:
    cuts=stone_cuts if obj is stone[0] else gold_cuts
    bm=refine(obj,cuts)
    meshes.append((obj,bm))
    print("D20_V2_MASTER_BASE",obj.name,len(bm.faces),"cuts",cuts,flush=True)
base=sum(len(bm.faces) for _,bm in meshes)
assert base==estimated,(base,estimated)
needed=(TARGET-base)//2
assert base+needed*2==TARGET
# Each poke transforms one triangle into THREE valid triangles, maintaining
# UV/material interpolation on the new generated mesh; no false instances.
stone_bm=next(bm for obj,bm in meshes if obj is stone[0])
stone_quota=min(max(0,(220000-len(stone_bm.faces))//2),len(stone_bm.faces),needed)
gold_bms=sorted([(obj,bm) for obj,bm in meshes if obj in gold],key=lambda x:x[0].name)
gold_capacity=sum(len(bm.faces) for _,bm in gold_bms)
if needed-stone_quota>gold_capacity:
    stone_quota+=needed-stone_quota-gold_capacity
assert stone_quota<=len(stone_bm.faces),(stone_quota,len(stone_bm.faces))
assert needed-stone_quota<=gold_capacity
quotas={stone[0].name:stone_quota}
remaining=needed-stone_quota
taken=0
for i,(obj,bm) in enumerate(gold_bms):
    n=(remaining-taken if i==len(gold_bms)-1 else int(remaining*len(bm.faces)/gold_capacity))
    assert n<=len(bm.faces)
    quotas[obj.name]=n
    taken+=n
assert taken==remaining,(taken,remaining)
def dispersed_faces(bm,count):
    face_list=list(bm.faces)
    assert 0<=count<=len(face_list)
    return [face_list[(i*len(face_list))//count] for i in range(count)] if count else []

for obj,bm in meshes:
    original_count=len(bm.faces)
    quota=quotas[obj.name]
    if quota:
        bmesh.ops.poke(bm,faces=dispersed_faces(bm,quota),offset=0.0,center_mode="MEAN_WEIGHTED")
    assert len(bm.faces)==original_count+2*quota
    bm.normal_update()
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()
    assert all(len(face.vertices)==3 for face in obj.data.polygons)
    print("D20_V2_FINAL_PART",obj.name,len(obj.data.polygons),flush=True)
after=sum(len(o.data.polygons) for o in objects)
assert after==TARGET,("Actual Blender triangle count mismatched",after)
stone_total=len(stone[0].data.polygons)
gold_total=after-stone_total
print("D20_V2_EXACT_GEOMETRY_BUDGET",{"source_triangles":source_triangles,
    "stone_cuts":stone_cuts,"gold_cuts":gold_cuts,
    "stone_triangles":stone_total,"gold_triangles":gold_total,
    "total_triangles":after},flush=True)

# Preserve face shading selection and original source material slots.
for obj in objects:
    assert obj.data.materials
    assert not any(m.name.lower().startswith("emissive") for m in obj.data.materials if m)
# Selecting ALL 21 die objects, not studio/floor/camera; export one die GLB.
bpy.ops.object.select_all(action="DESELECT")
for obj in objects:
    obj.select_set(True)
bpy.context.view_layer.objects.active=stone[0]
glb=OUT/"d20_obsidian_gold_master_500k.glb"
bpy.ops.export_scene.gltf(filepath=str(glb),export_format="GLB",use_selection=True,export_yup=True)
assert glb.stat().st_size > 1500000,("GLB too small",glb.stat().st_size)
print("D20_MASTER_EXPORTED_GLB",glb,glb.stat().st_size,flush=True)

# Real Cycles capture of the *same new mesh*. No generated illustration.
# Blender imported source textures/materials are left unchanged for parity.
floor_mat=bpy.data.materials.new("Studio_BlackVelvet_Only")
floor_mat.diffuse_color=(.018,.018,.020,1)
bpy.ops.mesh.primitive_plane_add(size=200,location=(0,0,-1.035))
floor=bpy.context.object
floor.name="Temporary_Studio_Black_Velvet"
floor.data.materials.append(floor_mat)
def area(name,pos,energy,dimensions,color):
    dat=bpy.data.lights.new(name,"AREA")
    dat.energy=energy
    dat.shape="RECTANGLE"
    dat.size,dat.size_y=dimensions
    dat.color=color
    ob=bpy.data.objects.new(name,dat)
    bpy.context.collection.objects.link(ob)
    ob.location=pos
    ob.rotation_euler=(-ob.location).to_track_quat("-Z","Y").to_euler()
area("LongCoolCard",(-3.5,1.2,5.0),340,(2.3,5),(.83,.90,1.0))
area("ThinGoldRim",(3,-.8,3.1),210,(.8,4.0),(1.0,.83,.59))
area("TopFill",(0,3.4,5.6),155,(3.0,1.6),(.95,.95,1.0))
world=bpy.data.worlds.new("Studio_True_Dark_Environment")
world.use_nodes=True
world.node_tree.nodes["Background"].inputs["Color"].default_value=(.018,.023,.029,1)
world.node_tree.nodes["Background"].inputs["Strength"].default_value=.6
sc=bpy.context.scene
sc.world=world
sc.render.engine="CYCLES"
sc.cycles.device="CPU"
sc.cycles.samples=20
# Blender 4.0 Debian package is built without Intel OpenImageDenoise:
# prevent Cycles from failing AFTER correct GLB has been exported.
bpy.context.view_layer.cycles.use_denoising=False
sc.render.resolution_x=720
sc.render.resolution_y=720
sc.render.resolution_percentage=100
sc.render.image_settings.file_format="PNG"
if bpy.app.version >= (4,0,0):
    sc.view_settings.view_transform="AgX"
camera_dat=bpy.data.cameras.new("Master_Review_Camera")
camera=bpy.data.objects.new("Master_Review_Camera",camera_dat)
bpy.context.collection.objects.link(camera)
camera_dat.type="ORTHO"
camera_dat.ortho_scale=3.0
camera.location=(3.5,-4.6,5.0)
camera.rotation_euler=(-camera.location).to_track_quat("-Z","Y").to_euler()
sc.camera=camera
# Preserve fully editable Blender source including original highpoly geometry.
blend=OUT/"d20_obsidian_gold_master_500k.blend"
bpy.ops.wm.save_as_mainfile(filepath=str(blend))
sc.render.filepath=str(OUT/"blender_cycles_master_500k.png")
bpy.ops.render.render(write_still=True)
assert (OUT/"blender_cycles_master_500k.png").stat().st_size>20000
